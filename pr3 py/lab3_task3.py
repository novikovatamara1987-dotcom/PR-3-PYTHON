
print("Сравнение срочных вкладов (ставки в % годовых)")
s = float(input("Введите сумму вклада, руб.: "))
p1 = float(input("Ставка по вкладу на 3 месяца, %: "))
p2 = float(input("Ставка по вкладу на 6 месяцев, %: "))
p3 = float(input("Ставка по вкладу на 1 год, %: "))

if s <= 0 or p1 < 0 or p2 < 0 or p3 < 0:
    print("Ошибка: сумма должна быть больше 0, ставки - не меньше 0.")
else:
    s1 = round(s * (1 + p1 / 100 * 3 / 12) ** 4, 2)  # 4 раза по 3 мес.
    s2 = round(s * (1 + p2 / 100 * 6 / 12) ** 2, 2)  # 2 раза по 6 мес.
    s3 = round(s * (1 + p3 / 100), 2)                # 1 раз на год

    print("Сумма через год:")
    print(f"  на 3 месяца:  {s1:.2f} руб. (доход {s1 - s:.2f} руб.)")
    print(f"  на 6 месяцев: {s2:.2f} руб. (доход {s2 - s:.2f} руб.)")
    print(f"  на 1 год:     {s3:.2f} руб. (доход {s3 - s:.2f} руб.)")

    # При равном доходе выбирается более короткий срок:
    # деньги раньше становятся доступны вкладчику
    if s1 == s2 == s3:
        print("Все три вклада одинаково выгодны.")
    elif s1 >= s2 and s1 >= s3:
        print("Наиболее выгоден вклад на 3 месяца.")
    elif s2 >= s3:
        print("Наиболее выгоден вклад на 6 месяцев.")
    else:
        print("Наиболее выгоден вклад на 1 год.")
