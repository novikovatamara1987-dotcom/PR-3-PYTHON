print("Тест по истории архитектуры")
print("В каком стиле построен собор Парижской Богоматери?")
print("1 - Барокко")
print("2 - Классицизм")
print("3 - Готика")

answer = input("Введите номер ответа (1, 2 или 3): ").strip()

if answer == "3":
    print("Верно! Собор Парижской Богоматери - памятник готики.")
elif answer == "1" or answer == "2":
    print("Неверно. Правильный ответ: 3 - Готика.")
else:
    print("Ошибка ввода: нужно ввести 1, 2 или 3.")
